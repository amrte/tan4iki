// Enemy line-up per stage: counts of [basic, fast, power, armor] (always 20)
function enemyMix(stage) {
  if (stage === 1) return [18, 2, 0, 0];
  const s = ((stage - 1) % LEVELS.length) + 1;
  const loop = Math.floor((stage - 1) / LEVELS.length);
  const armor = Math.min(8, Math.round((s - 1) * 0.3) + loop * 2);
  const power = Math.min(6, 1 + Math.floor(s / 5) + loop);
  const fast = Math.min(6, 2 + (s % 3) + Math.floor(s / 9));
  const basic = Math.max(0, 20 - armor - power - fast);
  return [basic, fast, power, 20 - basic - fast - power];
}
